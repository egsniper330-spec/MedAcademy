const KNOWN_BASE = new Set([
  'text', 'uuid', 'jsonb', 'integer', 'bigint', 'smallint', 'boolean',
  'timestamptz', 'timestamp', 'date', 'time', 'real', 'double', 'bytea',
  'tsvector', 'citext', 'inet', 'int', 'numeric', 'interval', 'oid',
  'name', 'character', 'char', 'varchar', 'json',
]);

function isEnumType(t) {
  return !KNOWN_BASE.has(t) && !/^(varchar|character|numeric)\(/.test(t) && !/\[\]/.test(t) && enums[t] !== undefined;
}

// ---------------------------------------------------------------------------
// Type conversion
// ---------------------------------------------------------------------------
// Which columns participate in indexes/unique/PK — TEXT cannot be indexed or
// UNIQUE in MySQL without a prefix length, so those columns become VARCHAR.
function isKeyed(col, table) {
  if (col.pk || col.unique) return true;
  if (table.primaryKey && table.primaryKey.includes(col.name)) return true;
  if (table.uniques.some((u) => u.columns && u.columns.includes(col.name))) return true;
  if (table.foreignKeys.some((f) => f.columns && f.columns.includes(col.name))) return true;
  if (inv.indexes.some((ix) => ix.table === table.name && ix.columns.replace(/\s+(ASC|DESC)\b/gi, '').split(',').map((x) => x.trim()).includes(col.name))) return true;
  return false;
}

function toMySqlType(col, table) {
  let t = col.type.trim();
  if (/^timestamp\s+with\s+time\s+zone$/i.test(t)) t = 'timestamptz';
  if (/^timestamp\s+without\s+time\s+zone$/i.test(t)) t = 'timestamp';

  if (isEnumType(t)) {
    const values = enums[t];
    const len = Math.max(16, ...values.map((v) => v.length));
    return { type: `VARCHAR(${len})`, enumName: t, values };
  }

  // Common lookup columns that deserve real VARCHAR sizing (and indexability)
  const NAME_SIZES = {
    email: 255,
    profile_email: 255,
    phone: 32,
    phone_e164: 32,
    phone_national: 32,
    phone_country_code: 16,
    phone_original: 32,
    code: 64,
    watermark_id: 64,
    installation_id: 64,
    device_fingerprint: 191,
    device_name: 191,
    full_name: 191,
    name: 191,
    title: 255,
    provider_video_id: 191,
    video_id: 191,
  };
  if (t === 'text' && NAME_SIZES[col.name]) return { type: `VARCHAR(${NAME_SIZES[col.name]})` };
  if (t === 'text' && isKeyed(col, table)) return { type: 'VARCHAR(191)' };

  switch (t) {
    case 'uuid': return { type: 'CHAR(36)' };
    case 'text': return { type: 'TEXT' };
    case 'character varying':
    case 'varchar': return { type: 'VARCHAR(255)' };
    case 'character':
    case 'char': return { type: 'CHAR(1)' };
    case 'integer':
    case 'int':
    case 'int4': return { type: 'INT' };
    case 'bigint':
    case 'int8': return { type: 'BIGINT' };
    case 'smallint':
    case 'int2': return { type: 'SMALLINT' };
    case 'oid': return { type: 'BIGINT' };
    case 'boolean': return { type: 'TINYINT(1)' };
    case 'jsonb':
    case 'json': return { type: 'JSON' };
    case 'timestamptz':
    case 'timestamp': return { type: 'DATETIME(6)' };
    case 'date': return { type: 'DATE' };
    case 'time': return { type: 'TIME' };
    case 'real': return { type: 'FLOAT' };
    case 'double':
    case 'double precision': return { type: 'DOUBLE' };
    case 'bytea': return { type: 'LONGBLOB' };
    case 'tsvector': return { type: 'TEXT' };
    case 'citext': return { type: 'VARCHAR(255)' };
    case 'inet': return { type: 'VARCHAR(45)' };
    case 'interval': return { type: 'VARCHAR(32)' };
    case 'name': return { type: 'VARCHAR(63)' };
    case 'numeric': return { type: 'DECIMAL(20,6)' };
    default: {
      const m = t.match(/^(varchar|character\s+varying)\((\d+)\)$/i);
      if (m) return { type: `VARCHAR(${m[2]})` };
      const m2 = t.match(/^numeric\((\d+),\s*(\d+)\)$/i);
      if (m2) return { type: `DECIMAL(${m2[1]},${m2[2]})` };
      const arr = t.match(/^(text|uuid|jsonb|integer|bigint|smallint)\[\]$/);
      if (arr) return { type: 'JSON' };
      return { type: t.toUpperCase(), unconverted: true };
    }
  }
}

// ---------------------------------------------------------------------------
// Default conversion
// ---------------------------------------------------------------------------
function toMySqlDefault(col, mysqlType) {
  const d = col.default;
  if (d === null || d === undefined) return null;
  let v = String(d).trim();

  // strip ::casts and ARRAY[] wrappers
  v = v.replace(/::[a-z_]+(\[\])?/gi, '');
  v = v.replace(/^ARRAY\[\s*\]/i, '[]');
  v = v.replace(/^ARRAY\[/i, '[');

  const upper = v.toUpperCase();
  if (/^NULL$/i.test(v)) return null;
  if (/^NOW\(\)$/i.test(v) || /^CURRENT_TIMESTAMP$/i.test(v)) return 'CURRENT_TIMESTAMP';
  if (/^GEN_RANDOM_UUID\(\)$/i.test(v) || /^UUID_GENERATE_V\d\(\)$/i.test(v)) return '(UUID())';
  if (/^TRUE$/i.test(v)) return '1';
  if (/^FALSE$/i.test(v)) return '0';
  if (/^NEXTVAL\(/.test(v)) return { expr: null, note: 'app-generated (sequence ' + v + ')' };
  if (/^PUBLIC\.NEXT_WATERMARK_ID\(\)/i.test(v)) return { expr: null, note: 'app-generated via watermark sequence table' };
  if (/^ENCODE\(GEN_RANDOM_BYTES\(/.test(v)) return { expr: null, note: 'app-generated random hex' };
  if (/^UPPER\(ENCODE\(GEN_RANDOM_BYTES\(/.test(v)) return { expr: null, note: 'app-generated random hex (upper)' };
  if (/^\(\s*NOW\(\)\s*\+\s*INTERVAL\s+'(\d+)\s*(HOURS?|DAYS?|MINUTES?|SECONDS?)'\s*\)$/i.test(v)) {
    const m = v.match(/INTERVAL\s+'(\d+)\s*(HOURS?|DAYS?|MINUTES?|SECONDS?)'/i);
    const unit = m[2].replace(/s$/i, '').toUpperCase();
    return `(CURRENT_TIMESTAMP + INTERVAL ${m[1]} ${unit})`;
  }
  if (/^-?\d+(\.\d+)?$/.test(v)) return v;
  // expression defaults for JSON columns (must come before the string branch)
  if (mysqlType === 'JSON') {
    if (/^\{\}$/.test(v)) return "'{}'";
    if (/^\[\]$/.test(v)) return "'[]'";
  }
  if (v.startsWith("'") && v.endsWith("'")) {
    const inner = v.slice(1, -1).replace(/''/g, "'");
    return `'${inner.replace(/'/g, "''")}'`;
  }
  return { expr: null, note: 'PG default not portable: ' + d };
}

// ---------------------------------------------------------------------------
// CHECK conversion (PG -> MySQL 8.0.16+/MariaDB 10.2+)
// ---------------------------------------------------------------------------
function toMySqlCheck(expr) {
  let e = expr.trim();
  // = ANY (ARRAY['a','b'])  ->  IN ('a','b')
  e = e.replace(/=\s*ANY\s*\(\s*ARRAY\s*\[\s*([^\]]*)\]\s*\)/gi, (mm, list) => {
    const vals = list.split(',').map((x) => x.trim().replace(/::[a-z_]+/gi, ''));
    return 'IN (' + vals.join(', ') + ')';
  });
  // Not portable if it uses PG-only constructs
  if (/::[a-z_]/i.test(e) || /->>/.test(e) || /ARRAY\s*\[/i.test(e) || /\bUSING\b/i.test(e)) return null;
  return e;
}

// ---------------------------------------------------------------------------
// Identifier escaping + constraint name hashing (MySQL limit: 64 chars)
// ---------------------------------------------------------------------------
const esc = (s) => '`' + s.replace(/`/g, '``') + '`';
function cname(prefix, parts) {
  const base = prefix + '_' + parts.join('_');
  return base.slice(0, 60);
}

// ---------------------------------------------------------------------------
// Topological ordering by FK dependencies
// ---------------------------------------------------------------------------
function orderTables(tables) {
  const byName = new Map(tables.map((t) => [t.name, t]));
  const done = new Set();
  const ordered = [];
  function visit(name, stack) {
    if (done.has(name)) return;
    if (stack.has(name)) return; // cycle — order broken; leave as-is
    stack.add(name);
    const t = byName.get(name);
    if (!t) return;
    const deps = new Set();
    t.foreignKeys.forEach((f) => {
      if (byName.has(f.refTable) && f.refTable !== name) deps.add(f.refTable);
    });
    t.columns.forEach((c) => {
      if (c.references && byName.has(c.references.table) && c.references.table !== name) deps.add(c.references.table);
    });
    deps.forEach((d) => visit(d, stack));
    stack.delete(name);
    done.add(name);
    ordered.push(t);
  }
  tables.forEach((t) => visit(t.name, new Set()));
  // append anything missed
  tables.forEach((t) => { if (!done.has(t.name)) ordered.push(t); });
  return ordered;
}

