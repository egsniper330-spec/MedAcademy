// ---------------------------------------------------------------------------
// Build schema.sql
// ---------------------------------------------------------------------------
const ordered = orderTables(tables);
const enumCols = []; // (table, column, values) for CHECK constraints

// PG GENERATED ALWAYS AS (...) STORED columns reproduced as MySQL generated
// columns. Keyed by "table.column" -> MySQL expression (column names escaped
// inside are backticked below).
const GENERATED_COLUMNS = {
  'enrollments.activation_method': '(`enrollment_method`)',
};

function columnDdl(col, table) {
  // Generated column
  if (GENERATED_COLUMNS[table.name + '.' + col.name]) {
    return `${esc(col.name)} VARCHAR(64) GENERATED ALWAYS AS ${GENERATED_COLUMNS[table.name + '.' + col.name]} STORED COMMENT 'pg: GENERATED ALWAYS AS (enrollment_method) STORED'`;
  }

  const conv = toMySqlType(col, table);
  const parts = [];
  let notes = [];

  if (conv.unconverted) notes.push('UNCONVERTED PG type: ' + col.type);

  if (col.pk && !table.primaryKey) {
    // single-column PK — inline
    parts.push(esc(col.name) + ' ' + conv.type + ' NOT NULL PRIMARY KEY');
    let d = toMySqlDefault(col, conv.type);
    if (d && d.expr !== undefined) {
      if (typeof d === 'object') { notes.push(d.note); }
      else parts.push('DEFAULT ' + d);
    }
    if (notes.length) parts.push("COMMENT '" + notes.join('; ').replace(/'/g, "''") + "'");
    return parts.join(' ');
  }

  parts.push(esc(col.name) + ' ' + conv.type);

  if (conv.enumName) {
    enumCols.push({ table: table.name, column: col.name, values: conv.values });
  }

  const d = toMySqlDefault(col, conv.type);
  if (d) {
    if (typeof d === 'object') {
      if (d.note) notes.push(d.note);
    } else {
      // MySQL only allows parenthesised defaults for TEXT/JSON columns
      const needsParens = /^(TEXT|JSON|LONGBLOB)/.test(conv.type);
      parts.push('DEFAULT ' + (needsParens ? '(' + d + ')' : d));
    }
  }
  if (col.notNull) parts.push('NOT NULL');
  if (col.unique && !col.pk) parts.push('UNIQUE');

  const pgNote = col.default ? 'pg_default: ' + col.default : null;
  if (pgNote) notes.push(pgNote);

  if (notes.length) parts.push("COMMENT '" + notes.join('; ').replace(/'/g, "''") + "'");
  return parts.join(' ');
}

let out = '';
out += `-- ===========================================================================
-- MedAcademy — MySQL/MariaDB schema (migration from Supabase/PostgreSQL)
-- Generated by: node backend/scripts/generate-mysql-schema.mjs
-- Source:       backend/scripts/schema-inventory.json (parsed from supabase/migrations)
-- Generated at: ${new Date().toISOString()}
--
-- REQUIREMENTS
--   MySQL 8.0.13+  OR  MariaDB 10.2.1+  (expression defaults, JSON, CHECK)
--   InnoDB, utf8mb4. All UUIDs stored as lowercase hex in CHAR(36).
--
-- CONVERSION NOTES
--   * UUIDs are CHAR(36) lowercase-hex strings; existing IDs are preserved
--     verbatim during data import (see MIGRATION_DATA_REQUIREMENTS.md).
--   * PG enums become VARCHAR(n) + CHECK constraints (name: chk_<table>_<col>).
--   * jsonb / text[] / uuid[] become JSON.
--   * timestamptz becomes DATETIME(6); the API layer always writes UTC.
--   * RLS policies are NOT representable in MySQL — they are enforced by the
--     PHP middleware (see docs/RPC_RLS_MAPPING.md).
--   * SECURITY DEFINER functions become PHP services/controllers.
--   * gen_random_bytes()/watermark defaults are generated by the app layer.
-- ===========================================================================

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

${USERS_TABLE}

`;

for (const t of ordered) {
  const lines = [];
  lines.push(`-- ===========================================================================`);
  lines.push(`-- TABLE: ${t.name}${t.schema ? ' (pg schema: ' + t.schema + ')' : ''}`);
  lines.push(`-- ===========================================================================`);
  lines.push(`CREATE TABLE IF NOT EXISTS ${esc(t.name)} (`);

  const colLines = [];
  for (const col of t.columns) {
    // generated column (enrollments.activation_method)
    if (col.type === '' && /generated/i.test(col.default || '')) continue;
    colLines.push('  ' + columnDdl(col, t));
  }

  const pk = t.primaryKey && t.primaryKey.length ? t.primaryKey : (t.columns.find((c) => c.pk) ? [t.columns.find((c) => c.pk).name] : null);
  if (pk) {
    colLines.push('  PRIMARY KEY (' + pk.map(esc).join(', ') + ')');
  }

  // unique constraints
  const seenUnique = new Set();
  for (const u of t.uniques) {
    if (!u.columns || !u.columns.length) continue;
    const key = u.columns.join(',');
    if (seenUnique.has(key)) continue;
    seenUnique.add(key);
    colLines.push('  ' + (u.name ? 'CONSTRAINT ' + esc(cname('uq', [t.name, ...u.columns])) + ' ' : '') + 'UNIQUE (' + u.columns.map(esc).join(', ') + ')');
  }

  // foreign keys
  const fkSeen = new Set();
  const emitFk = (cols, refTable, refCols, onDelete, name) => {
    const key = cols.join(',') + '>' + refTable;
    if (fkSeen.has(key)) return;
    fkSeen.add(key);
    let s = '  CONSTRAINT ' + esc(cname('fk', [t.name, cols[0]])) + ' FOREIGN KEY (' + cols.map(esc).join(', ') + ') REFERENCES ' + esc(refTable) + ' (' + refCols.map(esc).join(', ') + ')';
    if (onDelete) s += ' ON DELETE ' + onDelete.replace(/\s+/g, ' ').toUpperCase();
    colLines.push(s);
  };
  for (const f of t.foreignKeys) {
    if (!f.columns || !f.columns.length) continue;
    emitFk(f.columns, f.refTable, f.refColumns, f.onDelete, f.name);
  }
  for (const col of t.columns) {
    if (col.references && !col.pk) {
      emitFk([col.name], col.references.table, col.references.columns, col.references.onDelete, null);
    }
  }

  // table-level CHECK constraints (portable subset)
  let checkIdx = 0;
  for (const ck of t.checks) {
    const conv = toMySqlCheck(ck.expr || '');
    if (!conv) {
      lines.unshift(`-- NOTE: ${t.name} had a PG CHECK that is not portable: ${(ck.expr || '').slice(0, 100)}`);
      continue;
    }
    colLines.push('  CONSTRAINT ' + esc(cname('chk', [t.name, 'c' + checkIdx])) + ' CHECK (' + conv + ')');
    checkIdx++;
  }

  lines.push(colLines.join(',\n'));
  lines.push(') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;');
  lines.push('');
  out += lines.join('\n');
}

// ---- enum CHECK constraints ----
out += `-- ===========================================================================
-- ENUM CHECK CONSTRAINTS (replaces PG CREATE TYPE ... AS ENUM)
-- ===========================================================================
`;
for (const e of enumCols) {
  const vals = e.values.map((v) => "'" + v.replace(/'/g, "''") + "'").join(', ');
  out += `ALTER TABLE ${esc(e.table)} ADD CONSTRAINT ${esc(cname('chk', [e.table, e.column]))} CHECK (${esc(e.column)} IN (${vals}));\n`;
}

// ---- indexes ----
out += `
-- ===========================================================================
-- INDEXES (from PG CREATE INDEX; expression/partial indexes are noted and
-- moved to the application layer — MySQL cannot represent them directly)
-- ===========================================================================
`;
let skippedIdx = 0;
for (const ix of inv.indexes) {
  const bare = ix.columns.replace(/\s+(ASC|DESC)\b/gi, '').trim();
  if (/\bWHERE\b/i.test(bare)) {
    out += `-- SKIPPED (partial index): ${ix.name} ON ${ix.table} (${ix.columns})\n`;
    skippedIdx++;
    continue;
  }
  if (!/^[A-Za-z_][\w]*(, [A-Za-z_][\w]*)*$/.test(bare)) {
    out += `-- SKIPPED (expression index): ${ix.name} ON ${ix.table} (${ix.columns})\n`;
    skippedIdx++;
    continue;
  }
  const uniq = ix.unique ? 'UNIQUE ' : '';
  out += `CREATE ${uniq}INDEX ${esc(ix.name)} ON ${esc(ix.table)} (${bare.split(',').map((x) => esc(x.trim())).join(', ')});\n`;
}
if (skippedIdx) out += `-- (${skippedIdx} PG indexes not representable in MySQL — see docs)\n`;

out += TRIGGERS;

