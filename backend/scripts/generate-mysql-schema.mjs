#!/usr/bin/env node
/**
 * generate-mysql-schema.mjs
 * -------------------------
 * Converts the extracted MedAcademy PostgreSQL schema inventory
 * (backend/scripts/schema-inventory.json) into MySQL/MariaDB DDL.
 *
 * Conversion rules (all reversible and documented):
 *   uuid                 -> CHAR(36)                (IDs preserved as lowercase hex strings)
 *   text                 -> TEXT (or VARCHAR when a short literal default exists)
 *   varchar(n)           -> VARCHAR(n)
 *   integer / smallint   -> INT / SMALLINT
 *   bigint               -> BIGINT
 *   boolean              -> TINYINT(1)
 *   jsonb / text[]/uuid[]-> JSON
 *   timestamptz          -> DATETIME(6)             (app stores UTC)
 *   numeric(p,s)         -> DECIMAL(p,s)
 *   bytea                -> LONGBLOB
 *   tsvector             -> TEXT + FULLTEXT option  (search moved to app layer)
 *   PG enum              -> VARCHAR(n) + CHECK IN (...)
 *
 *   gen_random_uuid()    -> DEFAULT (UUID())
 *   now()                -> DEFAULT CURRENT_TIMESTAMP
 *   (now()+interval..)   -> DEFAULT (CURRENT_TIMESTAMP + INTERVAL .. HOUR/DAY)
 *   encode(gen_random_bytes(..),'hex') -> no DB default; generated by PHP
 *
 * Usage: node backend/scripts/generate-mysql-schema.mjs
 * Output: backend/database/schema.sql
 */
