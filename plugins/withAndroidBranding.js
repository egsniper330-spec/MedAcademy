// CommonJS — Expo config plugin (no ESM, no TypeScript).
// plugins/ is excluded from oxlint via .eslintignore.
//
// withAndroidBranding — makes the Android brand resources part of the
// source-controlled build instead of hand-written files under `android/`.
//
// THE BUG THIS FIXES (root cause, Android-only)
// ───────────────────────────────────────────────────────────────────────────
// The approved MedAcademy identity was regenerated into `assets/` (icon,
// adaptive foreground, monochrome layer, notification icon, splash), but Android
// kept showing the OLD branding on the launch screen and the launcher. Two
// independent gaps, not one:
//
//   1. NOTHING OWNS THE ANDROID SPLASH SCREEN.
//      `expo-splash-screen` is not installed and `app.json` has no `splash`
//      key, so no prebuild plugin writes `splashscreen_logo.png`,
//      `splashscreen_background` or `Theme.App.SplashScreen`. The files under
//      `android/app/src/main/res` were hand-written once (2026-09-19) and
//      `expo prebuild --clean` cannot replace them — it has no input to render
//      from. The legacy white background + old mark therefore persisted
//      indefinitely, and no amount of updating `assets/` could change it.
//
//   2. ON API 31+ THE LAUNCH SCREEN *IS* THE LAUNCHER ICON.
//      With no `android:windowSplashScreenAnimatedIcon`, the Android 12+
//      system splash falls back to drawing the app's launcher icon. So a stale
//      launcher icon produced a stale launch screen even where the splash
//      drawables were correct.
//
// Additionally, `android/` is generated output that had drifted: the mipmaps
// and notification icons were rasterized from the PREVIOUS identity and were
// never regenerated after the asset swap, because the build path this project
// uses is `gradlew assembleRelease` (no prebuild step).
//
// WHAT THIS PLUGIN DOES
//   Runs after every prebuild and writes EVERY Android brand resource from the
//   single approved vector master (scripts/brand/identity-paths.js) via
//   scripts/brand/android-brand-resources.js:
//
//     • launcher icon, round icon, adaptive foreground, monochrome layer,
//       notification icon — per density bucket, rendered (never upscaled)
//     • splashscreen_logo per density, fitted inside the Android 12 splash
//       safe circle so the mark cannot be clipped
//     • splash screen colours (brand navy in light, deep navy in night)
//     • Theme.App.SplashScreen with BOTH the pre-31 windowBackground and the
//       API 31+ windowSplashScreenBackground / windowSplashScreenAnimatedIcon
//
//   `android:windowSplashScreenAnimatedIcon` is the load-bearing item that
//   decouples the launch screen from the launcher icon.
//
// WHY A CONFIG PLUGIN (not a direct android/ edit)
//   android/ is generated by `expo prebuild`. A manual edit is wiped on the
//   next prebuild; this plugin re-applies the change every time, which is how
//   the rest of this repo's native patches are maintained. The SAME module is
//   also runnable directly against an existing checkout
//   (`node scripts/apply-android-branding.js`) because this project's build
//   path does not always run prebuild.

const path = require('path');
const fs = require('fs');

const {
  writeAndroidBrandResources,
} = require('../scripts/brand/android-brand-resources');

const withAndroidBranding = (config) => {
  // Resolve withDangerousMod from expo's own package tree so we always get the
  // SDK-compatible version, matching the other plugins in this directory.
  const expoRoot = path.dirname(require.resolve('expo/package.json'));
  const { withDangerousMod } = require(
    require.resolve('@expo/config-plugins', { paths: [expoRoot] })
  );

  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const resDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');
      if (!fs.existsSync(resDir)) return cfg;

      const { written, removed } = writeAndroidBrandResources(resDir, {
        log: (msg) => console.log('[withAndroidBranding] ' + msg),
      });

      console.log(
        '[withAndroidBranding] ' + written.length + ' resource(s) updated' +
        (removed.length ? ', ' + removed.length + ' stale file(s) removed' : '') +
        ' — launcher, adaptive, monochrome, notification and splash now match assets/'
      );
      return cfg;
    },
  ]);
};

module.exports = withAndroidBranding;
