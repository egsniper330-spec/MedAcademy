// CommonJS — Expo config plugin (no ESM, no TypeScript).
// plugins/ is excluded from oxlint via .eslintignore.
//
// withNetworkSecurityConfig — REAL Android TLS certificate pinning for the
// first-party API origin.
//
// THE BUG THIS FIXES
//   The repo already carries a complete, configured pin list in
//   app.json → expo.extra.medaSslPins / medaPinnedHosts:
//
//       medaPinnedHosts: ["api.medacademy.site"]
//       medaSslPins:     [<leaf SPKI>, <LE intermediate SPKI>, <backup>, <backup>]
//
//   iOS consumes them for real (plugins/ios/PinningURLProtocol.swift, injected
//   into Info.plist as MEDA_SPKI_PINS / MEDA_PINNED_HOSTS).
//
//   Android consumed them into android/gradle.properties as
//   apiSpkiPins / apiPinnedHosts — and then NOTHING read them. There was:
//     • no <network-security-config>                     (this file adds it)
//     • no OkHttp CertificatePinner / TrustManager       (never existed)
//     • no consumer of BuildConfig.API_SPKI_PINS         (hardcoded "")
//
//   Consequence on a real device: every TLS connection was validated only
//   against the SYSTEM TRUST STORE. Installing a proxy CA (a normal step in any
//   traffic inspector) was therefore sufficient to decrypt the API traffic and
//   read the JSON bodies — no tampering with the app required, because there was
//   no pin to violate. That is the reported "readable JSON in the inspector".
//
// WHY A NETWORK SECURITY CONFIG (and not an OkHttp CertificatePinner)
//   <pin-set> is enforced by the PLATFORM TLS stack (Conscrypt) for every
//   connection the app makes — RN fetch/OkHttp, WebView, ExoPlayer, the
//   VdoCipher SDK, and any future dependency. It is declarative, survives
//   prebuild, cannot be silently pruned by R8, and needs no app code to be
//   loaded or called. A hand-rolled pinner would only cover the call sites that
//   use it, and could be stripped or hooked.
//
// TRUST-ANCHOR POSTURE
//   The pinned domain-config lists ONLY <certificates src="system"/>. That means
//   a USER-INSTALLED CA is not a trust anchor for the API origin at all — the
//   "just install the proxy CA" attack fails at trust evaluation, before pinning
//   is even consulted. Pinning then additionally binds the identity to the
//   Let's Encrypt hierarchy so even a SYSTEM-level rogue CA cannot impersonate
//   the API.
//
//   Third-party origins (VdoCipher, YouTube, Google, Telegram) are deliberately
//   NOT pinned: they are not ours to pin and their rotation would brick video.
//   They keep the default base-config trust (system CAs).
//
// PIN-STABILITY NOTE (do not turn this into a bricking change)
//   <pin-set> passes when ANY pin matches ANY certificate in the chain. The pin
//   list includes the Let's Encrypt INTERMEDIATE, not only the leaf, so routine
//   90-day leaf rotation keeps working without an app update. `expiration` is a
//   maintenance reminder: after that date a pin-set mismatch no longer blocks
//   (Android then falls back to normal validation), so refresh the pins and the
//   date before then. Keep at least one CA-level pin at all times.

const path = require('path');
const fs = require('fs');

const CONFIG_RELATIVE = ['app', 'src', 'main', 'res', 'xml', 'network_security_config.xml'];

/** Android expects yyyy-MM-dd. Refresh with the pin list before this date. */
const PIN_EXPIRATION = '2028-06-01';

/** Base64 SPKI pins are exactly 32 bytes base64 = 44 chars. */
function validPins(raw) {
  return Array.isArray(raw)
    ? raw.filter((p) => typeof p === 'string' && p.trim().length === 44)
    : [];
}

function validHosts(raw) {
  return Array.isArray(raw)
    ? raw.filter((h) => typeof h === 'string' && h.trim().length > 0).map((h) => h.trim())
    : [];
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Build the network security config.
 *
 * base-config  → everything inherits: cleartext OFF, system CAs only.
 * domain-config→ the pinned first-party origin: cleartext OFF, system CAs only
 *                (NOT user CAs), plus the SPKI pin-set.
 */
function buildConfigXml(pins, hosts) {
  const lines = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!--',
    '  Generated by plugins/withNetworkSecurityConfig.js — do not edit by hand.',
    '  Expo prebuild regenerates android/, so this file is re-applied on every build.',
    '',
    '  Pins come from app.json → expo.extra.medaSslPins (same source of truth as',
    '  the iOS MEDA_SPKI_PINS Info.plist values). Each pin is the base64 SHA-256 of',
    '  a SubjectPublicKeyInfo (SPKI) in the production certificate chain.',
    '-->',
    '<network-security-config>',
    '  <base-config cleartextTrafficPermitted="false">',
    '    <trust-anchors>',
    '      <certificates src="system" />',
    '    </trust-anchors>',
    '  </base-config>',
  ];

  if (pins.length > 0 && hosts.length > 0) {
    lines.push('');
    lines.push('  <!-- First-party API origin: pinned + user CAs excluded -->');
    lines.push('  <domain-config cleartextTrafficPermitted="false">');
    for (const host of hosts) {
      lines.push(`    <domain includeSubdomains="true">${escapeXml(host)}</domain>`);
    }
    lines.push('    <trust-anchors>');
    lines.push('      <!-- system only: a user-installed (proxy) CA is never a trust');
    lines.push('           anchor for the API origin, independent of the pin-set -->');
    lines.push('      <certificates src="system" />');
    lines.push('    </trust-anchors>');
    lines.push(`    <pin-set expiration="${PIN_EXPIRATION}">`);
    for (const pin of pins) {
      lines.push(`      <pin digest="SHA-256">${escapeXml(pin.trim())}</pin>`);
    }
    lines.push('    </pin-set>');
    lines.push('  </domain-config>');
  }

  lines.push('</network-security-config>');
  lines.push('');
  return lines.join('\n');
}

/** Write res/xml/network_security_config.xml (survives prebuild via dangerous mod). */
function withNetworkSecurityConfigFile(config) {
  const expoRoot = path.dirname(require.resolve('expo/package.json'));
  const { withDangerousMod } = require(
    require.resolve('@expo/config-plugins', { paths: [expoRoot] })
  );

  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const pins = validPins(cfg.extra?.medaSslPins);
      const hosts = validHosts(cfg.extra?.medaPinnedHosts);
      const xmlPath = path.join(cfg.modRequest.platformProjectRoot, ...CONFIG_RELATIVE);
      fs.mkdirSync(path.dirname(xmlPath), { recursive: true });
      fs.writeFileSync(xmlPath, buildConfigXml(pins, hosts), 'utf8');

      if (pins.length > 0 && hosts.length > 0) {
        console.log(
          `[withNetworkSecurityConfig] pinned ${hosts.join(', ')} with ${pins.length} SPKI pin(s) ` +
            `(expires ${PIN_EXPIRATION}), cleartext disabled, user CAs excluded`
        );
      } else {
        console.log(
          '[withNetworkSecurityConfig] no medaSslPins/medaPinnedHosts configured — ' +
            'wrote cleartext-disabled base config only (pinning INERT)'
        );
      }
      return cfg;
    },
  ]);
}

/**
 * Point <application> at @xml/network_security_config.
 *
 * @param {import('@expo/config-plugins').ExpoConfig} config
 */
function withNetworkSecurityConfigManifest(config) {
  const expoRoot = path.dirname(require.resolve('expo/package.json'));
  const { withAndroidManifest } = require(
    require.resolve('@expo/config-plugins', { paths: [expoRoot] })
  );

  return withAndroidManifest(config, (cfg) => {
    const application = cfg.modResults?.manifest?.application?.[0];
    if (!application) return cfg;
    application.$ = application.$ || {};
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    // Explicit, belt-and-braces: the release manifest must never opt into
    // cleartext. (android/src/debug keeps its own true override for Metro.)
    application.$['android:usesCleartextTraffic'] = 'false';
    return cfg;
  });
}

const withNetworkSecurityConfig = (config) => {
  config = withNetworkSecurityConfigFile(config);
  config = withNetworkSecurityConfigManifest(config);
  return config;
};

module.exports = withNetworkSecurityConfig;

// Exposed for the regression test (tests/certificatePinning.test.cjs).
module.exports.__internal = {
  buildConfigXml,
  validPins,
  validHosts,
  PIN_EXPIRATION,
  CONFIG_RELATIVE,
};
