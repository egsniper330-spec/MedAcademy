  // MARK: — 10. DEVICECHECK (fallback when App Attest is unavailable) — hardened
  // ────────────────────────────────────────────────────────────────────────────
  // DCDevice generates a per-device token validated by Apple's servers.
  // Weaker than App Attest (proves real device, not app authenticity).
  // Used ONLY when App Attest is genuinely unavailable:
  //   • Simulator (DCAppAttestService.isSupported == false)
  //   • iOS < 14
  //   • A11 or older SoC (iPhone 8 and older)
  //
  // NOT used for transient App Attest server errors — those should be retried.
  //
  // Error code semantics:
  //   DEVICE_CHECK_UNSUPPORTED — genuine unavailability (simulator, non-Apple device)
  //   DEVICE_CHECK_ERROR       — token generation failure

  @objc(generateDeviceCheckToken:rejecter:)
  func generateDeviceCheckToken(
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard DCDevice.current.isSupported else {
      reject("DEVICE_CHECK_UNSUPPORTED", "DeviceCheck not supported on this device", nil)
      return
    }
    DCDevice.current.generateToken { tokenData, error in
      if let error = error {
        reject("DEVICE_CHECK_ERROR", error.localizedDescription, error)
        return
      }
      guard let data = tokenData else {
        reject("DEVICE_CHECK_ERROR", "generateToken returned nil", nil)
        return
      }
      resolve(data.base64EncodedString())
    }
  }

