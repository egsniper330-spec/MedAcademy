  // ────────────────────────────────────────────────────────────────────────────
  // MARK: — 8. BUNDLE / BINARY INTEGRITY (Anti-Tamper) — hardened
  // ────────────────────────────────────────────────────────────────────────────
  // Checks:
  //   A) MachO magic bytes — must be a valid ARM64/fat binary value
  //   B) MachO flags — CS_VALID flag in load commands (code-signing status)
  //   C) LC_ENCRYPTION_INFO / LC_ENCRYPTION_INFO_64 load command
  //      App Store binaries always contain this command (FairPlay encryption stub).
  //      Its absence means the binary was never through App Store processing,
  //      i.e. it was sideloaded, enterprise-resigned, or cracked.
  //      NOTE: Debug / development builds also lack this command. We combine
  //      this with CS_VALID and the release-channel check at JS layer.

  private func checkBundleIntegritySafe() -> Bool {
    // _MH_EXECUTE_HEADER is unreliable with the Xcode 15+ new linker (ld-prime).
    // The symbol exists but its Swift binding breaks under certain ASLR / LTO configs.
    // _dyld_get_image_header(0) is the canonical, always-correct way to get the
    // main executable's Mach-O header pointer — it accounts for the ASLR slide and
    // is guaranteed to point to the currently loaded image header.
    guard let rawHeader = _dyld_get_image_header(0) else {
      return false // extremely unlikely; fail-open to avoid false positives
    }
    // Reinterpret as mach_header_64 (all modern iOS devices are arm64)
    let header = rawHeader.withMemoryRebound(to: mach_header_64.self, capacity: 1) { $0 }

    // Check A: MachO header magic
    let magic = header.pointee.magic
    let validMagics: [UInt32] = [MH_MAGIC_64, MH_CIGAM_64, MH_MAGIC, MH_CIGAM, FAT_MAGIC, FAT_CIGAM]
    if !validMagics.contains(magic) { return true }

    // Check B: MachO flags — CS_VALID (0x1) indicates code signing is intact.
    // A resigner that patches the binary but fails to re-sign will leave CS_VALID unset.
    let flags = header.pointee.flags
    let CS_VALID: UInt32 = 0x00000001
    if (flags & CS_VALID) == 0 && flags != 0 { return true }

    // Check C: LC_ENCRYPTION_INFO / LC_ENCRYPTION_INFO_64 presence
    // App Store distributed binaries always have this; cracked/sideloaded ones do not.
    var encryptionFound = false
    let ncmds = Int(header.pointee.ncmds)
    var lcPtr = UnsafeRawPointer(header) + MemoryLayout<mach_header_64>.size
    for _ in 0..<ncmds {
      let lc = lcPtr.load(as: load_command.self)
      if lc.cmd == LC_ENCRYPTION_INFO || lc.cmd == LC_ENCRYPTION_INFO_64 {
        encryptionFound = true
        break
      }
      lcPtr = lcPtr + Int(lc.cmdsize)
    }
    // CS_DEBUGGED (0x10000000): set on debug/dev builds; skip encryption check for those.
    let CS_DEBUGGED: UInt32 = 0x10000000
    let isDebugBuild = (flags & CS_DEBUGGED) != 0
    if !encryptionFound && !isDebugBuild { return true }

    return false
  }

  // ────────────────────────────────────────────────────────────────────────────
  // MARK: — 9. APP ATTEST (iOS 14+ equivalent of Play Integrity) — hardened
  // ────────────────────────────────────────────────────────────────────────────
  // Flow: generateKey → attestKey (once, server-side) → generateAssertion (per-request).
  // Key lifecycle:
  //   • generateKey() creates a new Secure Enclave key and returns a keyId.
  //   • JS layer stores keyId in expo-secure-store.
  //   • On subsequent launches JS reads stored keyId and calls generateAssertion directly.
  //   • If assertKey() / generateAssertion() returns DCError.invalidKey, JS calls
  //     generateAppAttestKey again to regenerate (this method rejects with error code
  //     "APP_ATTEST_INVALID_KEY" so the JS layer can distinguish it from transient errors).
  //
  // Error code semantics:
  //   APP_ATTEST_UNAVAILABLE   — iOS < 14 (not a supported device for this check)
  //   APP_ATTEST_UNSUPPORTED   — Simulator or A11 and older chip (use DeviceCheck fallback)
  //   APP_ATTEST_INVALID_KEY   — Key invalidated by Apple; caller MUST regenerate
  //   APP_ATTEST_SERVER_ERROR  — Transient; caller should retry, not regenerate
  //   APP_ATTEST_KEY_ERROR     — Other key generation failure
  //   APP_ATTEST_ATTEST_ERROR  — Attestation failure (server or hardware error)
  //   APP_ATTEST_ASSERTION_ERROR — Assertion generation failure

  @objc(generateAppAttestKey:rejecter:)
  func generateAppAttestKey(
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard #available(iOS 14.0, *) else {
      reject("APP_ATTEST_UNAVAILABLE", "App Attest requires iOS 14+", nil)
      return
    }
    let service = DCAppAttestService.shared
    guard service.isSupported else {
      reject("APP_ATTEST_UNSUPPORTED", "App Attest not supported on this device — use DeviceCheck", nil)
      return
    }
    service.generateKey { keyId, error in
      if let error = error {
        reject("APP_ATTEST_KEY_ERROR", error.localizedDescription, error)
        return
      }
      guard let keyId = keyId else {
        reject("APP_ATTEST_KEY_ERROR", "generateKey returned nil keyId", nil)
        return
      }
      resolve(keyId)
    }
  }

  @objc(attestAppAttestKey:clientDataHash:resolver:rejecter:)
  func attestAppAttestKey(
    keyId: String,
    clientDataHash: String,
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard #available(iOS 14.0, *) else {
      reject("APP_ATTEST_UNAVAILABLE", "App Attest requires iOS 14+", nil)
      return
    }
    // Parameter validation — reject obviously malformed inputs immediately.
    // keyId must be a non-empty string (Apple returns a UUID-like identifier).
    // clientDataHash must be a non-empty base64 string that decodes to exactly 32 bytes (SHA-256).
    guard !keyId.isEmpty, keyId.count <= 256 else {
      reject("APP_ATTEST_INVALID_PARAM", "keyId must be a non-empty string ≤ 256 chars", nil)
      return
    }
    guard !clientDataHash.isEmpty, clientDataHash.count <= 512 else {
      reject("APP_ATTEST_INVALID_PARAM", "clientDataHash must be a non-empty base64 string ≤ 512 chars", nil)
      return
    }
    guard let hashData = Data(base64Encoded: clientDataHash), hashData.count == 32 else {
      reject("APP_ATTEST_INVALID_HASH", "clientDataHash must be base64-encoded SHA-256 (32 bytes)", nil)
      return
    }
    DCAppAttestService.shared.attestKey(keyId, clientDataHash: hashData) { attestObject, error in
      if let error = error {
        // Distinguish permanent key invalidation from transient server errors
        let nsErr = error as NSError
        if nsErr.domain == "DCErrorDomain" {
          if nsErr.code == DCError.invalidKey.rawValue {
            reject("APP_ATTEST_INVALID_KEY", "Key invalidated — regenerate required", error)
            return
          }
          if nsErr.code == DCError.serverUnavailable.rawValue {
            reject("APP_ATTEST_SERVER_ERROR", "Apple attestation server unavailable — retry", error)
            return
          }
        }
        reject("APP_ATTEST_ATTEST_ERROR", error.localizedDescription, error)
        return
      }
      guard let obj = attestObject else {
        reject("APP_ATTEST_ATTEST_ERROR", "attestKey returned nil object", nil)
        return
      }
      resolve(obj.base64EncodedString())
    }
  }

  @objc(generateAppAttestAssertion:challenge:resolver:rejecter:)
  func generateAppAttestAssertion(
    keyId: String,
    challenge: String,
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard #available(iOS 14.0, *) else {
      reject("APP_ATTEST_UNAVAILABLE", "App Attest requires iOS 14+", nil)
      return
    }
    // Parameter validation — keyId and challenge must be non-empty and within
    // reasonable size bounds to prevent memory exhaustion or bridge abuse.
    guard !keyId.isEmpty, keyId.count <= 256 else {
      reject("APP_ATTEST_INVALID_PARAM", "keyId must be a non-empty string ≤ 256 chars", nil)
      return
    }
    // Challenge is a server-issued nonce (typically 32–128 bytes when base64-encoded).
    // Cap at 1024 chars to guard against oversized input from a compromised JS layer.
    guard !challenge.isEmpty, challenge.count <= 1024 else {
      reject("APP_ATTEST_INVALID_CHALLENGE", "challenge must be a non-empty string ≤ 1024 chars", nil)
      return
    }
    guard let challengeData = challenge.data(using: .utf8) else {
      reject("APP_ATTEST_INVALID_CHALLENGE", "challenge must be a valid UTF-8 string", nil)
      return
    }
    // SHA-256 hash required by App Attest assertion API
    let hash = Data(SHA256.hash(data: challengeData))
    DCAppAttestService.shared.generateAssertion(keyId, clientDataHash: hash) { assertionData, error in
      if let error = error {
        let nsErr = error as NSError
        // Permanent key invalidation: JS must regenerate the key then re-attest
        if nsErr.domain == "DCErrorDomain", nsErr.code == DCError.invalidKey.rawValue {
          reject("APP_ATTEST_INVALID_KEY", "Key invalidated — regenerate required", error)
          return
        }
        if nsErr.domain == "DCErrorDomain", nsErr.code == DCError.serverUnavailable.rawValue {
          reject("APP_ATTEST_SERVER_ERROR", "Apple assertion server unavailable — retry", error)
          return
        }
        reject("APP_ATTEST_ASSERTION_ERROR", error.localizedDescription, error)
        return
      }
      guard let data = assertionData else {
        reject("APP_ATTEST_ASSERTION_ERROR", "generateAssertion returned nil", nil)
        return
      }
      resolve(data.base64EncodedString())
    }
  }

