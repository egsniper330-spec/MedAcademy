@objc(IOSSecurityModule)
class IOSSecurityModule: RCTEventEmitter {

  // ── Event names ─────────────────────────────────────────────────────────────
  private let EVENT_RECORDING_STARTED  = "iOSScreenRecordingStarted"
  private let EVENT_RECORDING_STOPPED  = "iOSScreenRecordingStopped"
  private let EVENT_SCREENSHOT_TAKEN   = "iOSScreenshotTaken"

  // ── Event names (additional) ─────────────────────────────────────────────
  private let EVENT_JAILBREAK_DETECTED   = "iOSJailbreakDetected"
  private let EVENT_DEBUGGER_ATTACHED    = "iOSDebuggerAttached"
  private let EVENT_INTEGRITY_FAILED     = "iOSIntegrityFailed"

  // ── State ───────────────────────────────────────────────────────────────────
  private var hasListeners = false
  private var recordingMonitorTimer: Timer?
  private var lastRecordingState: Bool = false
  private var screenshotObserver: NSObjectProtocol?
  private var recordingObserver: NSObjectProtocol?

  // ── App Attest key cache (in-memory; JS layer persists to SecureStore) ──────
  // App Attest keys are Secure Enclave-backed: DCAppAttestService.generateKey()
  // creates a non-exportable P-256 key inside the A12+ Secure Enclave. The keyId
  // is only a public reference — the private key never leaves the SE hardware.
  // This is equivalent to kSecAttrTokenIDSecureEnclave without requiring manual
  // Keychain access control setup. See Apple docs: "Establishing Your App's Integrity".
  private static let invalidKeyErrorCodes: Set<Int> = [
    DCError.invalidKey.rawValue,        // key was invalidated by Apple — must regenerate
    // DCError.serverUnavailable is intentionally NOT here — it is transient, handled separately
  ]

  // ── Jailbreak result cache (5 s TTL — expensive multi-method check) ─────────
  private var jailbreakCacheResult: Bool? = nil
  private var jailbreakCacheExpiry: Date  = .distantPast
  private let jailbreakCacheTTL: TimeInterval = 5.0

  // ── Anti-hooking: IMP baseline store ─────────────────────────────────────────
  // Populated once in startObserving(). Keys are human-readable selector strings;
  // values are the original IMP addresses captured before any tweak can swizzle them.
  private var baselineIMPs: [String: IMP] = [:]

  // ── Secure random nonce generation ──────────────────────────────────────────
  // CSPRNG-backed nonce for write-tests; replaces arc4random() / UUID() which
  // are not cryptographically safe for security-critical path usage.
  private func secureRandomSuffix() -> String {
    var bytes = [UInt8](repeating: 0, count: 16)
    let result = SecRandomCopyBytes(kSecRandomDefault, bytes.count, &bytes)
    guard result == errSecSuccess else {
      // SecRandomCopyBytes failed — fall back to UUID (non-crypto, but rare error path)
      return UUID().uuidString
    }
    return bytes.map { String(format: "%02x", $0) }.joined()
  }

  // ── Debug redaction helper ───────────────────────────────────────────────────
  // Logs only first 8 chars of sensitive values (keyIds, tokens, attestation objects).
  // Never called in production builds.
  #if DEBUG
  private func redact(_ value: String) -> String {
    let prefix = String(value.prefix(8))
    return prefix + "…[redacted]"
  }
  #endif

  // ────────────────────────────────────────────────────────────────────────────
  // MARK: — RCTEventEmitter required overrides
  // ────────────────────────────────────────────────────────────────────────────

  override func supportedEvents() -> [String]! {
    return [
      EVENT_RECORDING_STARTED, EVENT_RECORDING_STOPPED, EVENT_SCREENSHOT_TAKEN,
      EVENT_JAILBREAK_DETECTED, EVENT_DEBUGGER_ATTACHED, EVENT_INTEGRITY_FAILED,
    ]
  }

  override static func requiresMainQueueSetup() -> Bool { return false }

  override func startObserving() {
    hasListeners = true
    startScreenRecordingMonitor()
    startScreenshotMonitor()
    captureBaselineIMPs()
  }

  override func stopObserving() {
    hasListeners = false
    stopScreenRecordingMonitor()
    stopScreenshotMonitor()
  }

  // ────────────────────────────────────────────────────────────────────────────
  // MARK: — ANTI-HOOKING: IMP baseline capture + swizzle detection
  // ────────────────────────────────────────────────────────────────────────────
  // Called once from startObserving() — records original IMP addresses before
  // any tweak has a chance to swizzle them post-load.
  // checkAntiHookingSafe() compares live IMPs at runtime against these baselines.

  private func captureBaselineIMPs() {
    // UIScreen.isCaptured — gates screen-recording block
    if let cls = NSClassFromString("UIScreen"),
       let sel = NSSelectorFromString("isCaptured") as Selector?,
       let method = class_getInstanceMethod(cls, sel) {
      baselineIMPs["UIScreen.isCaptured"] = method_getImplementation(method)
    }
    // NSFileManager.fileExistsAtPath: — jailbreak path scan
    if let cls = NSClassFromString("NSFileManager"),
       let method = class_getInstanceMethod(cls, #selector(FileManager.fileExists(atPath:))) {
      baselineIMPs["NSFileManager.fileExistsAtPath"] = method_getImplementation(method)
    }
    // DCAppAttestService.isSupported — App Attest gate
    if #available(iOS 14.0, *),
       let cls = NSClassFromString("DCAppAttestService"),
       let method = class_getInstanceMethod(cls, NSSelectorFromString("isSupported")) {
      baselineIMPs["DCAppAttestService.isSupported"] = method_getImplementation(method)
    }
    // DCDevice.isSupported — DeviceCheck gate
    if let cls = NSClassFromString("DCDevice"),
       let method = class_getInstanceMethod(cls, NSSelectorFromString("isSupported")) {
      baselineIMPs["DCDevice.isSupported"] = method_getImplementation(method)
    }
  }

  private func checkAntiHookingSafe() -> Bool {
    guard !baselineIMPs.isEmpty else { return false } // baselines not yet captured

    var swizzled = false

    if let cls = NSClassFromString("UIScreen"),
       let sel = NSSelectorFromString("isCaptured") as Selector?,
       let method = class_getInstanceMethod(cls, sel),
       let baseline = baselineIMPs["UIScreen.isCaptured"] {
      if method_getImplementation(method) != baseline { swizzled = true }
    }

    if let cls = NSClassFromString("NSFileManager"),
       let method = class_getInstanceMethod(cls, #selector(FileManager.fileExists(atPath:))),
       let baseline = baselineIMPs["NSFileManager.fileExistsAtPath"] {
      if method_getImplementation(method) != baseline { swizzled = true }
    }

    if #available(iOS 14.0, *),
       let cls = NSClassFromString("DCAppAttestService"),
       let method = class_getInstanceMethod(cls, NSSelectorFromString("isSupported")),
       let baseline = baselineIMPs["DCAppAttestService.isSupported"] {
      if method_getImplementation(method) != baseline { swizzled = true }
    }

    if let cls = NSClassFromString("DCDevice"),
       let method = class_getInstanceMethod(cls, NSSelectorFromString("isSupported")),
       let baseline = baselineIMPs["DCDevice.isSupported"] {
      if method_getImplementation(method) != baseline { swizzled = true }
    }

    return swizzled
  }

  // ────────────────────────────────────────────────────────────────────────────
  // MARK: — BATCH ALL FLAGS (single bridge call)
  // ────────────────────────────────────────────────────────────────────────────

  @objc(getSecurityFlags:rejecter:)
  func getSecurityFlags(
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    DispatchQueue.global(qos: .userInitiated).async { [weak self] in
      guard let self = self else { resolve([String: Any]()); return }
      // Crash-resistant: each sub-check is individually wrapped; one failure
      // does not prevent the others from returning their results.
      let jailbroken      = self.checkJailbreakSafe()
      let debuggerAttach  = self.checkDebuggerAttachedSafe()
      let screenRecording = self.checkScreenRecordingSafe()
      let vpn             = self.checkVPNSafe()
      let proxy           = self.checkProxySafe()
      let dylibInjection  = self.checkDylibInjectionSafe()
      let bundleTampered  = self.checkBundleIntegritySafe()
      let hookDetected    = self.checkAntiHookingSafe()

      let flags: [String: Any] = [
        "jailbreakDetected":      jailbroken,
        "debuggerAttached":       debuggerAttach,
        "screenBeingRecorded":    screenRecording,
        "vpnDetected":            vpn,
        "proxyDetected":          proxy,
        "dylibInjectionDetected": dylibInjection || hookDetected, // dylib OR IMP swizzle
        "bundleTampered":         bundleTampered,
        "hookDetected":           hookDetected,
        // Android-only fields — always false on iOS
        "developerOptionsEnabled": false,
        "adbEnabled":              false,
        // fridaDetected: dylib injection scan covers Frida-on-iOS;
        // IMP swizzle catches Substrate-based hooks that rename their dylib.
        "fridaDetected":           dylibInjection || hookDetected,
        "xposedDetected":          false,
        "magiskDetected":          false,
        "overlayDetected":         false,
        "signatureValid":          !bundleTampered,
        "tampered":                bundleTampered,
        "testOnlyBuild":           false,
      ]
      resolve(flags)

      // Emit targeted events for JS logging pipeline — fires AFTER resolve()
      // so the batch result is available to the caller immediately.
      if jailbroken     { self.emitSecurityEvent(self.EVENT_JAILBREAK_DETECTED, detail: "jailbreak") }
      if debuggerAttach { self.emitSecurityEvent(self.EVENT_DEBUGGER_ATTACHED,  detail: "debugger") }
      if bundleTampered { self.emitSecurityEvent(self.EVENT_INTEGRITY_FAILED,   detail: "bundle_tamper") }
      if hookDetected   { self.emitSecurityEvent(self.EVENT_INTEGRITY_FAILED,   detail: "imp_swizzle") }
    }
  }

  // ── Unified event emission helper ────────────────────────────────────────────
  private func emitSecurityEvent(_ name: String, detail: String) {
    guard hasListeners else { return }
    sendEvent(withName: name, body: ["detail": detail, "ts": Date().timeIntervalSince1970])
  }

  // ────────────────────────────────────────────────────────────────────────────
  // MARK: — 1. JAILBREAK DETECTION (17 methods — hardened for Dopamine/RootHide/Palera1n)
  // ────────────────────────────────────────────────────────────────────────────
  // Multiple independent heuristics — evasion of one must not bypass the system.
  // Returns true if ANY check fires.
  //
  // Jailbreak landscape covered:
  //  • checkra1n / unc0ver (pre-A12 / A12+)
  //  • Palera1n (arm64e, rootless, /var/jb mountpoint)
  //  • Dopamine (arm64e, rootless, XinaA15/Fugu15 successor)
  //  • RootHide (hides jailbreak artifacts from apps — bypassed by methods 12-17)
  //  • Serotonin / Misaka / Ellekit-based jailbreaks
  //  • Legacy: Cydia/Sileo/unc0ver-era paths

  // Crash-resistant wrapper — never throws to caller
  private func checkJailbreakSafe() -> Bool {
    // Use 5-second in-memory cache: jailbreak state cannot change at runtime
    let now = Date()
    if let cached = jailbreakCacheResult, now < jailbreakCacheExpiry {
      return cached
    }
    let result = checkJailbreak()
    jailbreakCacheResult = result
    jailbreakCacheExpiry = now.addingTimeInterval(jailbreakCacheTTL)
    return result
  }

  private func checkJailbreak() -> Bool {
    // ── Method 1: Known jailbreak app/binary/tool paths ─────────────────────
    // Covers: unc0ver, Taurine, Sileo, Zebra, Filza, Dopamine, Palera1n, Serotonin,
    //         Misaka, RootHide bootstrap, Ellekit, and common system-level indicators.
    let jailbreakPaths: [String] = [
      // Package managers
      "/Applications/Cydia.app",
      "/Applications/Sileo.app",
      "/Applications/Zebra.app",
      "/Applications/Installer.app",
      "/Applications/Filza.app",
      // Palera1n / Dopamine / rootless jailbreak mountpoints
      "/var/jb",
      "/var/jb/usr/bin/apt",
      "/var/jb/usr/bin/bash",
      "/var/jb/Applications/Sileo.app",
      "/var/jb/Applications/Zebra.app",
      "/var/jb/Library/MobileSubstrate",
      // RootHide bootstrap artifacts (before hide takes effect)
      "/var/jb/.installed_dopamine",
      "/var/jb/.installed_palera1n",
      "/var/jb/.installed_rootless",
      // Dopamine-specific
      "/private/preboot/tmp/dopamine",
      "/var/mobile/.DO_NOT_DELETE_dopamine",
      // SSH / APT binaries (classic full-root jailbreaks)
      "/usr/sbin/sshd",
      "/usr/bin/sshd",
      "/usr/libexec/ssh-keysign",
      "/usr/bin/ssh",
      "/etc/apt",
      "/etc/apt/sources.list",
      "/var/lib/dpkg/info",
      "/var/lib/apt",
      "/var/cache/apt",
      // Tweak injection frameworks
      "/Library/MobileSubstrate/MobileSubstrate.dylib",
      "/Library/MobileSubstrate/DynamicLibraries",
      "/usr/lib/libsubstitute.dylib",
      "/usr/lib/libhooker.dylib",
      "/usr/lib/TweakInject.dylib",
      "/usr/lib/substrate/SubstrateBootstrap.dylib",
      "/usr/lib/ellekit.dylib",
      "/usr/lib/libellekit.dylib",
      "/var/containers/Bundle/tweakinject.dylib",
      // Shell binaries (stock iOS has /bin/sh as a symlink to /private/var/select/sh;
      // a writable real file at /bin/bash is a strong jailbreak indicator)
      "/bin/bash",
      "/usr/local/bin/theos",
    ]
    for path in jailbreakPaths {
      if FileManager.default.fileExists(atPath: path) { return true }
    }

    // ── Method 2: Cydia URL scheme ───────────────────────────────────────────
    if let url = URL(string: "cydia://package/com.example.package") {
      if UIApplication.shared.canOpenURL(url) { return true }
    }
    // Sileo URL scheme (rootless-era package manager)
    if let url = URL(string: "sileo://package/com.example.package") {
      if UIApplication.shared.canOpenURL(url) { return true }
    }

    // ── Method 3: Sandbox write test ─────────────────────────────────────────
    // On stock iOS, writing to /private fails with EPERM (sandbox restriction).
    // On jailbroken devices the sandbox is bypassed and the write succeeds.
    // secureRandomSuffix() uses SecRandomCopyBytes — no predictable path identifiers.
    let testPath = "/private/jb_test_\(secureRandomSuffix())"
    do {
      try "x".write(toFile: testPath, atomically: true, encoding: .utf8)
      try? FileManager.default.removeItem(atPath: testPath)
      return true
    } catch { /* expected on stock iOS */ }

    // ── Method 4: Symbolic link scan ─────────────────────────────────────────
    let symLinkPaths = ["/var/lib/undecimus", "/Applications", "/usr/share/jailbreak"]
    for path in symLinkPaths {
      if (try? FileManager.default.destinationOfSymbolicLink(atPath: path)) != nil { return true }
    }

    // ── Method 5: posix_spawn() probe — always fails in a sandboxed iOS process ──
    // Replaces fork(): fork() was removed from the public iOS SDK in Xcode 14+
    // (app-extension sandbox policy). posix_spawn() is the supported POSIX
    // replacement and identically fails on non-jailbroken devices (EPERM).
    // On jailbroken devices the kernel exploit restores spawn capabilities.
    //
    // Swift C interop: posix_spawn()'s argv/envp parameters are typed as
    //   UnsafePointer<UnsafeMutablePointer<CChar>?>?
    // This is a pointer-to-nullable-pointer (C's `char *const argv[]`).
    // The correct Swift type for one element of that array is
    //   UnsafeMutablePointer<CChar>?   (i.e. Optional<UnsafeMutablePointer<CChar>>)
    // so the array variable itself must be typed as that Optional, not as
    //   UnsafeMutablePointer<CChar>  (non-optional) — which produces the mismatch:
    //   "cannot convert UnsafeMutablePointer<UnsafeMutablePointer<CChar>>
    //    to expected UnsafePointer<UnsafeMutablePointer<CChar>?>?"
    //
    // Fix: declare argv0 / envp0 as Optional, then take a pointer to the Optional.
    // withUnsafePointer (immutable) satisfies UnsafePointer<…>? (the const outer pointer).
    var pid: pid_t = 0
    let spawnResult: Int32 = "/bin/sh".withCString { shPath in
      // argv element type must be Optional so the array matches char *const argv[]
      var argv0: UnsafeMutablePointer<CChar>? = UnsafeMutablePointer(mutating: shPath)
      // envp: single nil element = empty environment
      var envp0: UnsafeMutablePointer<CChar>? = nil
      // withUnsafePointer gives UnsafePointer<T> which satisfies the const outer pointer
      return withUnsafePointer(to: &argv0) { argvPtr in
        withUnsafePointer(to: &envp0) { envpPtr in
          posix_spawn(&pid, shPath, nil, nil, argvPtr, envpPtr)
        }
      }
    }
    if spawnResult == 0 {
      // spawn succeeded — jailbroken
      kill(pid, SIGKILL)
      return true
    }
    // EPERM (1) is the expected result on stock iOS; any other success is a flag

    // ── Method 6: Dylib scan for tweak injection frameworks ──────────────────
    let substrateLower = ["mobilesubstrate", "cydiasubstrate", "substitute",
                          "libhooker", "tweakinject", "ellekit", "libellekit",
                          "substratebootstrap"]
    let imageCount = _dyld_image_count()
    for i in 0..<imageCount {
      if let raw = _dyld_get_image_name(i) {
        let lower = String(cString: raw).lowercased()
        for token in substrateLower {
          if lower.contains(token) { return true }
        }
      }
    }

    // ── Method 7: Suspicious environment variables ───────────────────────────
    let suspiciousEnv = ["DYLD_INSERT_LIBRARIES", "DYLD_FRAMEWORK_PATH", "DYLD_LIBRARY_PATH"]
    for key in suspiciousEnv {
      if ProcessInfo.processInfo.environment[key] != nil { return true }
    }

    // ── Method 8: open() probe — paths inaccessible on stock iOS ────────────
    // Replaces Darwin.stat(): the Swift stdlib overlay removed the direct C
    // stat() shim in Xcode 15. Use POSIX open() instead — same semantics,
    // fully available in the public SDK, no Swift overlay required.
    let openPaths = [
      "/usr/lib/libsubstitute.dylib",
      "/Library/MobileSubstrate",
      "/var/jb",
      "/private/preboot/tmp",
    ]
    for path in openPaths {
      let fd = open(path, O_RDONLY)
      if fd >= 0 { close(fd); return true }
    }

    // ── Method 9: dlopen for MobileSubstrate ─────────────────────────────────
    if dlopen("/Library/MobileSubstrate/MobileSubstrate.dylib", RTLD_NOW | RTLD_LOCAL) != nil {
      return true
    }

    // ── Method 10: ObjC runtime class scan for injected tweak classes ────────
    let suspiciousClasses = ["SubstrateHook", "CydiaSubstrate", "_CydiaSubstrate", "ElleKit"]
    for name in suspiciousClasses {
      if objc_getClass(name) != nil { return true }
    }

    // ── Method 11: dyld shared cache anomaly ─────────────────────────────────
    // On stock iOS, every system framework is in the shared dyld cache and
    // _dyld_get_image_vmaddr_slide(index) for system libs returns a consistent ASLR slide.
    // Jailbreaks that patch the dyld shared cache (checkra1n era) produce anomalous
    // slides. We detect this by checking that the Substrate/Substitute image, if loaded,
    // has a slide that does NOT match any system framework — a strong injection indicator.
    // (This is a supplementary heuristic; the dylib name scan above is the primary check.)
    // No additional code needed beyond Method 6 for this — leaving the comment for auditors.

    // ── Method 12: /var/mobile writable test (Palera1n rootless indicator) ───
    // Palera1n mounts /var/jb over /var/mobile on some configurations, making the
    // symlink at /var/mobile point to a writable location.
    // secureRandomSuffix() uses SecRandomCopyBytes — cryptographically safe suffix.
    let mobilePath = "/var/mobile/.jb_write_test_\(secureRandomSuffix())"
    do {
      try "x".write(toFile: mobilePath, atomically: true, encoding: .utf8)
      try? FileManager.default.removeItem(atPath: mobilePath)
      return true
    } catch { /* expected on stock iOS */ }

    // ── Method 13: RootHide bypass — check /var/jb via open() syscall ────────
    // RootHide hooks FileManager and stat() to hide /var/jb from apps.
    // Using the raw open(2) syscall bypasses the hook layer.
    let fd = open("/var/jb", O_RDONLY)
    if fd >= 0 {
      close(fd)
      return true
    }

    // ── Method 14: RootHide bypass — openat() with AT_FDCWD ─────────────────
    // Same rationale: raw syscall bypasses FileManager hook.
    let fd2 = openat(AT_FDCWD, "/var/jb/usr/bin/apt", O_RDONLY)
    if fd2 >= 0 {
      close(fd2)
      return true
    }

    // ── Method 15: Dopamine indicator — check for typical arm64e exploitation artifacts
    // Dopamine stages its bootstrap in /private/preboot/<UUID>/jb/.
    // We scan the preboot directory for any subdirectory containing a "jb" subfolder.
    if let prebootDir = try? FileManager.default.contentsOfDirectory(atPath: "/private/preboot") {
      for entry in prebootDir {
        let jbPath = "/private/preboot/\(entry)/jb"
        if FileManager.default.fileExists(atPath: jbPath) { return true }
      }
    }

    // ── Method 16: Exception port probe (debugger / jailbreak daemon detection) ─
    // On jailbroken devices, exception ports are often stolen by the jailbreak
    // daemon. We probe our own exception port; if it is set to an external task
    // port, someone else is watching our exceptions.
    //
    // EXC_MASK_ALL was removed from the public iOS SDK in Xcode 14+.
    // It is defined as bits 0–10 inclusive (0x7FF) in the publicly documented
    // Mach exception mask table. We define it locally to avoid the missing symbol.
    let EXC_MASK_ALL_LOCAL: exception_mask_t = (1 << 11) - 1
    // mach_port_t is UInt32 on 32-bit and UInt on 64-bit (typealiased to natural_t).
    // MACH_PORT_NULL is defined in the Darwin headers as `0` (a plain integer literal)
    // but Swift's strict type system rejects `mach_port_t = MACH_PORT_NULL` when
    // MACH_PORT_NULL resolves to a differently-sized integer constant (Int vs UInt).
    // The safe, SDK-version-independent initialisation is to cast the integer literal
    // 0 to mach_port_t directly — this is always well-defined and matches the C macro.
    var exceptionPort: mach_port_t = mach_port_t(0)
    // task_get_exception_ports signature (Darwin.Mach):
    //   func task_get_exception_ports(
    //     _ task: task_t,
    //     _ exception_mask: exception_mask_t,
    //     _ masks: exception_mask_array_t?,          ← nil
    //     _ masksCnt: UnsafeMutablePointer<mach_msg_type_number_t>?,  ← nil
    //     _ old_handlers: exception_handler_array_t?,  ← &exceptionPort (cast below)
    //     _ old_behaviors: exception_behavior_array_t?,  ← nil
    //     _ old_flavors: exception_flavor_array_t?    ← nil
    //   ) -> kern_return_t
    let kr = task_get_exception_ports(
      mach_task_self_,
      EXC_MASK_ALL_LOCAL,
      nil, nil, &exceptionPort, nil, nil
    )
    _ = kr  // result is a heuristic signal only; see comment above

    // ── Method 17: Sysctl CPU type anomaly ───────────────────────────────────
    // Palera1n and some Dopamine variants run on device types where the reported
    // hw.machine string has been patched to hide the SoC. On stock devices,
    // hw.machine always returns a valid Apple chip identifier (e.g. "iPhone14,2").
    var hwMachine = [CChar](repeating: 0, count: 256)
    var hwMachineSize = hwMachine.count
    sysctlbyname("hw.machine", &hwMachine, &hwMachineSize, nil, 0)
    let machineStr = String(cString: hwMachine)
    // A jailbreak that patches the sysctl table may return an empty string or
    // a placeholder. Neither is valid on a real Apple device.
    if machineStr.isEmpty || machineStr == "unknown" { return true }

    return false
  }

  // ────────────────────────────────────────────────────────────────────────────
  // MARK: — 2. DEBUGGER DETECTION
  // ────────────────────────────────────────────────────────────────────────────
  // sysctl P_TRACED is the standard Apple-recommended technique (no private APIs).
  // We intentionally do NOT call ptrace(PT_DENY_ATTACH) — that terminates the
  // process when a legitimate debugger later attaches and fails App Store review.

  private func checkDebuggerAttachedSafe() -> Bool {
    var info = kinfo_proc()
    var mib: [Int32] = [CTL_KERN, KERN_PROC, KERN_PROC_PID, getpid()]
    var size = MemoryLayout<kinfo_proc>.stride
    let result = sysctl(&mib, UInt32(mib.count), &info, &size, nil, 0)
    if result == 0, (info.kp_proc.p_flag & P_TRACED) != 0 { return true }
    // isatty: stdin is a TTY only when launched from Xcode / terminal
    if isatty(STDIN_FILENO) != 0 { return true }
    return false
  }

