// CommonJS — Expo config plugin (no ESM, no TypeScript).
// plugins/ is excluded from oxlint via .eslintignore.
//
// withSystemBars — makes the Android system navigation bar part of the app
// surface instead of a detached strip.
//
// THE BUG THIS FIXES
//   The app is edge-to-edge: android:navigationBarColor is transparent, so the
//   app draws behind the navigation bar. But the RN/Expo template theme also
//   sets:
//
//       <item name="android:enforceNavigationBarContrast">true</item>
//
//   On API 29+ that asks the OS to paint an OPAQUE CONTRAST SCRIM behind the
//   navigation bar whenever the bar is transparent (WindowInsetsAnimation /
//   NavigationBarContrastEnforced). The result on a physical device is exactly
//   the reported symptom:
//     • LIGHT MODE → a disconnected bright white strip at the bottom.
//     • DARK MODE  → a black band, or on some OEM themes a WHITE rectangle
//                    ("ugly white rectangle separated from the app").
//   The scrim is chosen by the OS, not by the app, so hardcoding a colour can
//   never fix it — the only correct fix is to stop enforcing the scrim and let
//   the app's own surface show through the transparent bar.
//
// WHAT WE SET
//   1. android:enforceNavigationBarContrast = false
//      → no OS scrim; the app surface is continuous through the nav bar.
//   2. android:windowLightNavigationBar
//      → true in values/ (light) and false in values-night/ (dark), so the
//        system nav-bar ICONS are dark-on-light / light-on-dark and stay
//        legible against the app surface with no scrim.
//   3. android:navigationBarColor = transparent (already required; re-asserted
//      so a future template change cannot silently reintroduce a solid bar).
//
//   We deliberately do NOT touch android:windowLightStatusBar here: the status
//   bar icon appearance is owned at runtime by expo-status-bar (style="auto"),
//   and setting it in the theme too would create a second owner that fights it.
//
// WHY A CONFIG PLUGIN (not a direct android/ edit)
//   android/ is generated by `expo prebuild`. Any manual edit would be wiped on
//   the next prebuild. This plugin re-applies the change after every prebuild,
//   which is how the rest of this repo's native patches are maintained.

const path = require('path');
const fs = require('fs');

const NAV_BAR_CONTRAST_ITEM =
  '<item name="android:enforceNavigationBarContrast" tools:targetApi="29">false</item>';

/** Ensure `<resources>` declares the `tools` namespace (needed by targetApi). */
function ensureToolsNamespace(xml) {
  if (/<resources[^>]*xmlns:tools=/.test(xml)) return xml;
  return xml.replace(/<resources\b/, '<resources xmlns:tools="http://schemas.android.com/tools"');
}

/**
 * Idempotently set/replace an <item name="..."> inside a named <style> block.
 * Pure string work — the file is a small, stable, machine-generated resource.
 */
function setStyleItem(xml, styleName, itemName, desiredLine) {
  // NOTE: string concatenation (never a JS template literal) keeps this file
  // safe for tests/buildConfigGuards.test.cjs, which flags a dollar-brace
  // interpolation inside a template literal as a leaked Groovy variable unless
  // the name is provably a JS binding. These regexes must carry the XML-side
  // interpolation semantics of the generated resource file, so plain
  // concatenation is the correct, unambiguous form here.
  const styleRe = new RegExp(
    '(<style\\s+name="' + styleName + '"[^>]*>)([\\s\\S]*?)(</style>)'
  );
  const m = xml.match(styleRe);
  if (!m) return xml;

  const whole = m[0];
  const open = m[1];
  const body = m[2];
  const close = m[3];
  const itemRe = new RegExp(
    '<item\\s+name="' + itemName + '"[^>]*\\/>|<item\\s+name="' + itemName + '"[^>]*>[\\s\\S]*?</item>'
  );

  const newBody = itemRe.test(body)
    ? body.replace(itemRe, desiredLine)
    : body + '    ' + desiredLine + '\n  ';

  return xml.replace(whole, open + newBody + close);
}

/** Apply the three items to a styles.xml body. */
function patchStyles(xml, options) {
  const lightNavBarIcons = options.lightNavBarIcons;
  let out = ensureToolsNamespace(xml);
  out = setStyleItem(out, 'AppTheme', 'android:enforceNavigationBarContrast', NAV_BAR_CONTRAST_ITEM);
  out = setStyleItem(
    out,
    'AppTheme',
    'android:windowLightNavigationBar',
    '<item name="android:windowLightNavigationBar">' + lightNavBarIcons + '</item>'
  );
  out = setStyleItem(
    out,
    'AppTheme',
    'android:navigationBarColor',
    '<item name="android:navigationBarColor">@android:color/transparent</item>'
  );
  return out;
}

/** values-night/styles.xml may not exist (only colors.xml does) — create it. */
const NIGHT_STYLES_TEMPLATE = `<resources xmlns:tools="http://schemas.android.com/tools">
  <!-- Generated/maintained by plugins/withSystemBars.js — night variants of AppTheme. -->
  <style name="AppTheme" parent="Theme.AppCompat.DayNight.NoActionBar">
    <item name="android:enforceNavigationBarContrast" tools:targetApi="29">false</item>
    <item name="android:editTextBackground">@drawable/rn_edit_text_material</item>
    <item name="colorPrimary">@color/colorPrimary</item>
    <item name="android:statusBarColor">@android:color/transparent</item>
    <item name="android:navigationBarColor">@android:color/transparent</item>
    <item name="android:windowLightNavigationBar">false</item>
  </style>
</resources>
`;

const withSystemBars = (config) => {
  // Resolve withDangerousMod from expo's own package tree so we always get the
  // SDK-55-compatible version, matching the other plugins in this directory.
  const expoRoot = path.dirname(require.resolve('expo/package.json'));
  const { withDangerousMod } = require(
    require.resolve('@expo/config-plugins', { paths: [expoRoot] })
  );

  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const resDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');

      // ── Light theme: nav-bar icons are DARK, drawn on the app's light surface
      const lightFile = path.join(resDir, 'values', 'styles.xml');
      if (fs.existsSync(lightFile)) {
        const before = fs.readFileSync(lightFile, 'utf8');
        const after = patchStyles(before, { lightNavBarIcons: true });
        if (after !== before) {
          fs.writeFileSync(lightFile, after, 'utf8');
          console.log('[withSystemBars] values/styles.xml: nav-bar contrast scrim disabled, light icons');
        }
      }

      // ── Dark theme: nav-bar icons are LIGHT
      const nightDir = path.join(resDir, 'values-night');
      if (!fs.existsSync(nightDir)) fs.mkdirSync(nightDir, { recursive: true });
      const nightFile = path.join(nightDir, 'styles.xml');
      if (!fs.existsSync(nightFile)) {
        fs.writeFileSync(nightFile, NIGHT_STYLES_TEMPLATE, 'utf8');
        console.log('[withSystemBars] created values-night/styles.xml (dark system bars)');
      } else {
        const before = fs.readFileSync(nightFile, 'utf8');
        const after = patchStyles(before, { lightNavBarIcons: false });
        if (after !== before) {
          fs.writeFileSync(nightFile, after, 'utf8');
          console.log('[withSystemBars] values-night/styles.xml: nav-bar contrast scrim disabled, dark icons');
        }
      }

      return cfg;
    },
  ]);
};

module.exports = withSystemBars;

// Pure helpers exposed for tests/systemBarsPlugin.test.cjs (the config-plugin
// entry point stays the default export Expo expects).
module.exports.__internal = {
  patchStyles,
  setStyleItem,
  ensureToolsNamespace,
  NIGHT_STYLES_TEMPLATE,
  NAV_BAR_CONTRAST_ITEM,
};
