#!/usr/bin/env node
/**
 * Android DEBUG ↔ Metro cleartext — localhost:8081 via `adb reverse`.
 *
 * THE BUG THIS LOCKS DOWN
 *   A debug APK on a real tablet failed at startup with
 *
 *     CLEARTEXT communication to localhost not permitted by network security
 *     policy
 *
 *   while `adb reverse tcp:8081 tcp:8081` was confirmed working and Metro was
 *   listening on 8081. The debug manifest already carried
 *   android:usesCleartextTraffic="true", so the naive read of the situation
 *   ("the flag is missing") was wrong.
 *
 *   The actual cause: on API 24+ a <network-security-config> OVERRIDES
 *   android:usesCleartextTraffic. This repo's manifest references
 *   @xml/network_security_config (certificate pinning), and that config declares
 *   <base-config cleartextTrafficPermitted="false">. Metro's plain-HTTP request
 *   to localhost was therefore refused by the platform before any JS executed,
 *   no matter what the debug manifest attribute said.
 *
 * THE FIX THESE CHECKS PROTECT
 *   plugins/withNetworkSecurityConfig.js now also writes a DEBUG build-type
 *   resource overlay at android/app/src/debug/res/xml/network_security_config.xml.
 *   Resource merging gives src/debug precedence over src/main, so:
 *     • DEBUG  → the release config + ONE loopback-only domain-config that
 *                permits cleartext (localhost, 127.0.0.1, 10.0.2.2);
 *     • RELEASE→ untouched: base cleartext false, HTTPS enforced, pins intact,
 *                and src/debug is not merged at all.
 *
 *   It is generated by the plugin (not hand-edited in android/), so it survives
 *   `expo prebuild --clean`.
 *
 * Run: node tests/metroCleartextDebug.test.cjs
 */

'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const exists = (rel) => fs.existsSync(path.join(ROOT, rel));

const plugin = require(path.join(ROOT, 'plugins', 'withNetworkSecurityConfig.js'));
const internals = plugin.__internal;
const expo = JSON.parse(read('app.json')).expo;
const pins = internals.validPins(expo.extra?.medaSslPins);
const hosts = internals.validHosts(expo.extra?.medaPinnedHosts);

let passed = 0;
const failures = [];
function check(name, fn) {
  try {
    fn();
    passed += 1;
    console.log(`  ok    ${name}`);
  } catch (e) {
    failures.push(`${name}: ${e.message}`);
    console.log(`  FAIL  ${name}\n        ${e.message}`);
  }
}

const MAIN_XML_REL = path.join('android', 'app', 'src', 'main', 'res', 'xml', 'network_security_config.xml');
const DEBUG_XML_REL = path.join('android', ...internals.DEBUG_CONFIG_RELATIVE);
const MANIFEST_REL = path.join('android', 'app', 'src', 'main', 'AndroidManifest.xml');

console.log('── A. The plugin generates the debug overlay in the debug source set ──');
{
  check('A1: the debug overlay path is the debug build-type source set', () => {
    assert.deepEqual(internals.DEBUG_CONFIG_RELATIVE, [
      'app', 'src', 'debug', 'res', 'xml', 'network_security_config.xml',
    ]);
    // A release build merges src/main + src/<flavor> only — never src/debug.
    assert.ok(internals.DEBUG_CONFIG_RELATIVE[1] === 'src');
    assert.ok(internals.DEBUG_CONFIG_RELATIVE[2] === 'debug');
  });

  check('A2: the cleartext exception list is loopback-only (no wildcard, no API host)', () => {
    const domains = internals.DEBUG_CLEARTEXT_DOMAINS;
    assert.deepEqual(domains, ['localhost', '127.0.0.1', '10.0.2.2']);
    for (const d of domains) {
      assert.ok(!d.includes('*'), `${d} must not be a wildcard`);
      assert.ok(!hosts.includes(d), `${d} must not be a production host`);
    }
  });

  check('A3: the plugin writes the debug overlay (durable through prebuild)', () => {
    const src = read(path.join('plugins', 'withNetworkSecurityConfig.js'));
    assert.ok(/DEBUG_CONFIG_RELATIVE/.test(src), 'debug path constant present');
    assert.ok(
      /fs\.writeFileSync\(debugXmlPath, buildDebugConfigXml\(pins, hosts\), 'utf8'\)/.test(src),
      'the dangerous mod writes the debug overlay on every prebuild'
    );
    assert.ok(
      /withDangerousMod\(config, \[\s*'android'/.test(src),
      'the write happens in an android dangerous mod (survives prebuild)'
    );
  });

  check('A4: the debug overlay on disk matches the generator (not hand-edited)', () => {
    assert.ok(exists(DEBUG_XML_REL), `${DEBUG_XML_REL} is missing — run the plugin/prebuild`);
    assert.equal(read(DEBUG_XML_REL), internals.buildDebugConfigXml(pins, hosts));
  });
}

console.log('── B. DEBUG permits Metro on localhost only ──');
{
  const debugXml = read(DEBUG_XML_REL);

  check('B1: exactly one cleartext-permitting domain-config exists', () => {
    const n = (debugXml.match(/cleartextTrafficPermitted="true"/g) || []).length;
    assert.equal(n, 1, `expected exactly one true, found ${n}`);
  });

  check('B2: the base posture in DEBUG is still cleartext-disabled', () => {
    assert.ok(/<base-config cleartextTrafficPermitted="false">/.test(debugXml));
  });

  check('B3: localhost, its IP and the emulator loopback are permitted', () => {
    const block = debugXml.slice(debugXml.indexOf('cleartextTrafficPermitted="true"'));
    for (const host of ['localhost', '127.0.0.1', '10.0.2.2']) {
      assert.ok(
        new RegExp(`<domain includeSubdomains="false">${host.replace(/\./g, '\\.')}</domain>`).test(block),
        `${host} missing from the cleartext domain-config`
      );
    }
  });

  check('B4: the exception is not scoped to subdomains (loopback only)', () => {
    const block = debugXml.slice(debugXml.indexOf('cleartextTrafficPermitted="true"'));
    assert.ok(!/includeSubdomains="true"/.test(block), 'no subdomain wildcard in the debug exception');
  });

  check('B5: the production API host does NOT get cleartext in DEBUG', () => {
    for (const host of hosts) {
      const re = new RegExp(
        `cleartextTrafficPermitted="true"[\\s\\S]*?<domain[^>]*>${host.replace(/\./g, '\\.')}</domain>`
      );
      assert.ok(!re.test(debugXml), `${host} must stay HTTPS-only even in debug`);
    }
  });

  check('B6: DEBUG keeps the pin-set and the system-only trust anchors', () => {
    assert.ok(/<pin-set expiration="/.test(debugXml), 'pin-set dropped from the debug config');
    assert.ok(debugXml.includes(internals.PIN_EXPIRATION));
    for (const pin of pins) assert.ok(debugXml.includes(pin), 'debug config dropped a configured pin');
    assert.ok(!/src="user"/.test(debugXml), 'user CAs must stay excluded in debug');
    assert.ok(
      (debugXml.match(/<certificates src="system" \/>/g) || []).length >= 2,
      'base and pinned domains keep system-only anchors'
    );
  });
}

console.log('── C. RELEASE keeps the strict posture ──');
{
  const mainXml = read(MAIN_XML_REL);
  const manifest = read(MANIFEST_REL);

  check('C1: the release config permits NO cleartext anywhere', () => {
    assert.ok(!/cleartextTrafficPermitted="true"/.test(mainXml));
    assert.ok(/<base-config cleartextTrafficPermitted="false">/.test(mainXml));
  });

  check('C2: the release config is regression-free (generator output unchanged)', () => {
    assert.equal(mainXml, internals.buildConfigXml(pins, hosts));
  });

  check('C3: the manifest keeps cleartext off and points at the config', () => {
    assert.ok(/android:networkSecurityConfig="@xml\/network_security_config"/.test(manifest));
    assert.ok(/android:usesCleartextTraffic="false"/.test(manifest));
  });

  check('C4: the debug exception cannot leak into release resource merging', () => {
    // Both files share the same resource name; only the source set differs.
    assert.ok(DEBUG_XML_REL.includes(path.join('src', 'debug')));
    assert.ok(!MAIN_XML_REL.includes(path.join('src', 'debug')));
  });

  check('C5: no manifest-level cleartext opt-in was added to main', () => {
    assert.ok(
      !/android:usesCleartextTraffic="true"/.test(manifest),
      'main manifest must never enable cleartext'
    );
  });
}

console.log('── D. Wiring: the plugin is actually applied by Expo ──');
{
  check('D1: withNetworkSecurityConfig is registered in app.json plugins', () => {
    const plugins = expo.plugins || [];
    assert.ok(
      plugins.some((p) => (Array.isArray(p) ? p[0] : p) === './plugins/withNetworkSecurityConfig'),
      'plugin not registered — a prebuild would emit neither config'
    );
  });

  check('D2: the plugin exports the debug builder used above', () => {
    assert.equal(typeof internals.buildDebugConfigXml, 'function');
  });
}

// ─── Summary ────────────────────────────────────────────────────────────────

console.log(`\n${passed} assertions passed${failures.length ? ` — ${failures.length} FAILED` : ''}.`);
if (failures.length) {
  failures.forEach((f) => console.log(`  ✗ ${f}`));
  process.exitCode = 1;
} else {
  console.log('Metro debug-cleartext regression suite: OK\n');
}
